/**
 * service 层错误消息 → HTTP 状态码：**单一真相源**。
 *
 * 路由内的 sendServiceError 与兜底的 errorHandler 都从这里取状态码。
 * 两处各写一份正则会漂移，而漂移的表现正是「该 403 的变成 500」：
 * 只要有一个抛错点换了措辞（例如把「无权访问」写成「无权发消息到」），
 * 另一处没跟上就漏判。所以规则只留一份，并且由
 * test/http-errors.test.ts 逐条覆盖**真实抛错文案**，新增文案必须同时补进那张表。
 *
 * 分类只看**消息前缀族**，不绑定具体动作词：
 *   1. 权限拒绝（一律以「无权」开头：查看 / 发消息到 / 管理成员 / 删除 / 委派 / 取消 / 审批）→ 403
 *   2. 对象不存在（不存在 / 无法恢复 / 无法删除）→ 404
 *   3. 调用方把请求写错了（参数、业务规则、配置）→ 400
 *
 * ⚠️ 判据要克制：这里用的是**具体词**，不是「已」「未」这类单字。单字会把服务端自身的
 * 故障一起吞成 400 —— 例如 `ActionService 未注入（wiring 缺失）`、`写入通道尚未装配`
 * 是服务端装配错误，必须留给兜底给 500，否则"服务端炸了"会被伪装成"用户传错了"。
 *
 * 认不出来的返回 undefined：路由继续 next(err)，由兜底按 500 处理。
 */
export function serviceErrorStatus(message: string): number | undefined {
  // 1. 权限：前缀族，不是某一个动作
  if (/无权/.test(message)) return 403;

  // 2. 目标不存在（含"想做但对象没了"：无法恢复 / 无法删除）
  if (/不存在|无法恢复|无法删除/.test(message)) return 404;

  // 3. 调用方错误
  //    参数校验      ：非法 / 缺少 / 必须 / 不是
  //    业务规则冲突  ：不能 / 没有 / 无需 / 已经（already）/ 未轮到 —— 操作与当前状态不符
  //    状态冲突      ：已存在 / 已关闭 / 已过期
  //    配置写错      ：未知 / 可选：/ 被拒绝（内联 MCP、技能目录的策略拒绝）/ 解析失败
  if (
    /非法|缺少|必须|不是|不能|没有|无需|已经|未轮到|已存在|已关闭|已过期|未知|可选：|被拒绝|解析失败/.test(
      message,
    )
  ) {
    return 400;
  }

  return undefined;
}
